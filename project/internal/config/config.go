// Пакет config хранит настройки приложения.
// Правило: настройки приходят ИЗВНЕ (переменные окружения), а не «зашиты» в код.
package config

import "os" // os.Getenv читает переменные окружения операционной системы

// Config — структура (набор полей) со всеми настройками.
// Поля с большой буквы — «экспортируемые»: видны из других пакетов.
type Config struct {
	Addr          string // адрес HTTP-сервера, например ":8080"
	DBPath        string // путь к файлу базы SQLite
	UploadDir     string // папка, куда складываем загруженные файлы
	AdminUser     string // логин администратора (создаётся при первом запуске)
	AdminPassword string // пароль администратора (в БД попадёт только его bcrypt-хеш)
}

// Load собирает настройки: переменная окружения, а если её нет — значение по умолчанию.
func Load() Config { // возвращаем структуру по значению — она маленькая, копия дешёвая
	return Config{
		Addr:          getEnv("APP_ADDR", ":8080"),          // порт можно поменять: APP_ADDR=:9000
		DBPath:        getEnv("DB_PATH", "data/app.db"),     // база лежит в папке data/
		UploadDir:     getEnv("UPLOAD_DIR", "data/uploads"), // файлы отдельно от базы
		AdminUser:     getEnv("ADMIN_USER", "admin"),        // логин по умолчанию
		AdminPassword: getEnv("ADMIN_PASSWORD", "admin123"), // ОБЯЗАТЕЛЬНО смените на реальном сервере!
	}
}

// getEnv — маленький помощник: «значение переменной или запасной вариант».
func getEnv(key, fallback string) string { // два параметра одного типа можно писать через запятую
	if v := os.Getenv(key); v != "" { // короткая форма if: сначала присваивание, потом условие
		return v // переменная задана и непуста — используем её
	}
	return fallback // иначе — значение по умолчанию
}
